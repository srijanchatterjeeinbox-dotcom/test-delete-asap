let hasWarnedGeminiQuota = false;

/**
 * Builds alternating contents for Gemini generateContent API
 */
function buildGeminiContents(userPrompt, conversationHistory = []) {
  const contents = [];
  if (Array.isArray(conversationHistory) && conversationHistory.length > 0) {
    let lastRole = null;
    for (const item of conversationHistory) {
      const rawRole = (item.role === 'user' || item.role === 'inbound') ? 'user' : 'model';
      const text = String(item.text || item.body || item.content || '').trim();
      if (!text) continue;
      if (rawRole === lastRole) {
        contents[contents.length - 1].parts[0].text += `\n${text}`;
      } else {
        contents.push({ role: rawRole, parts: [{ text }] });
        lastRole = rawRole;
      }
    }
  }

  if (contents.length > 0 && contents[contents.length - 1].role === 'user') {
    contents[contents.length - 1].parts[0].text += `\n${String(userPrompt)}`;
  } else {
    contents.push({ role: 'user', parts: [{ text: String(userPrompt) }] });
  }

  return contents;
}

/**
 * Builds alternating messages for Claude API
 */
function buildClaudeMessages(userPrompt, conversationHistory = []) {
  const messages = [];
  if (Array.isArray(conversationHistory) && conversationHistory.length > 0) {
    let lastRole = null;
    for (const item of conversationHistory) {
      const rawRole = (item.role === 'user' || item.role === 'inbound') ? 'user' : 'assistant';
      const text = String(item.text || item.body || item.content || '').trim();
      if (!text) continue;
      if (rawRole === lastRole) {
        messages[messages.length - 1].content += `\n${text}`;
      } else {
        messages.push({ role: rawRole, content: text });
        lastRole = rawRole;
      }
    }
  }

  if (messages.length > 0 && messages[messages.length - 1].role === 'user') {
    messages[messages.length - 1].content += `\n${String(userPrompt)}`;
  } else {
    messages.push({ role: 'user', content: String(userPrompt) });
  }

  return messages;
}

async function callGemini(systemPrompt, userPrompt, preferredModel, conversationHistory = []) {
  const geminiKey = process.env.GEMINI_API_KEY;
  if (!geminiKey) return null;

  const modelsToTry = [
    preferredModel || process.env.GEMINI_MODEL || 'gemini-3.8-flash',
    'gemini-3.8-flash',
    'gemini-2.5-flash',
    'gemini-2.5-flash-lite'
  ].filter(Boolean);

  const uniqueModels = [...new Set(modelsToTry)];
  const contents = buildGeminiContents(userPrompt, conversationHistory);

  for (const model of uniqueModels) {
    try {
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'x-goog-api-key': geminiKey
          },
          signal: AbortSignal.timeout(7000),
          body: JSON.stringify({
            systemInstruction: {
              parts: [{ text: systemPrompt }]
            },
            contents,
            generationConfig: {
              temperature: 0.4,
              maxOutputTokens: 1000
            }
          })
        }
      );

      const data = await response.json();
      if (response.ok && data.candidates?.[0]?.content?.parts) {
        const text = data.candidates[0].content.parts
          .map(part => part.text || '')
          .join('\n')
          .trim();
        if (text) return text;
      } else if (response.status === 402 || response.status === 429 || data?.error?.status === 'RESOURCE_EXHAUSTED') {
        if (!hasWarnedGeminiQuota) {
          hasWarnedGeminiQuota = true;
          console.warn(`[AI Service] Gemini API quota/credits depleted (${response.status}). Using local DPHC AI Information Assistant.`);
        }
        break;
      } else if (!hasWarnedGeminiQuota && data?.error) {
        hasWarnedGeminiQuota = true;
        console.warn(`[AI Service] Gemini API response (${response.status}): ${data.error.message.slice(0, 160)}... Using local DPHC AI Information Assistant.`);
      }
    } catch (_) {
      // Continue to next model
    }
  }

  return null;
}

async function callClaude(systemPrompt, userPrompt, conversationHistory = []) {
  const anthropicKey = process.env.ANTHROPIC_API_KEY;
  if (!anthropicKey) return null;

  try {
    const messages = buildClaudeMessages(userPrompt, conversationHistory);
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'x-api-key': anthropicKey,
        'anthropic-version': '2023-06-01'
      },
      signal: AbortSignal.timeout(7000),
      body: JSON.stringify({
        model: process.env.ANTHROPIC_MODEL || 'claude-3-5-haiku-latest',
        max_tokens: 800,
        system: systemPrompt,
        messages
      })
    });

    const data = await response.json();
    if (response.ok && data.content) {
      return data.content.map(item => item.text || '').join('\n').trim();
    }
  } catch (_) {}

  return null;
}

